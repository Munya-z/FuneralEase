using FuneralEase.Domain.Subscriptions;

namespace FuneralEase.Application.Common.Interfaces;

/// <summary>
/// Application-layer abstraction over the billing provider (Paystack in production).
/// The Infrastructure layer supplies the concrete implementation.
/// </summary>
public interface IBillingProvider
{
    /// <summary>
    /// Initialises a payment transaction and returns the provider checkout URL.
    /// The consumer redirects the user there to complete payment.
    /// </summary>
    Task<InitializeTransactionResult> InitializeTransactionAsync(
        InitializeTransactionRequest request,
        CancellationToken cancellationToken = default);

    /// <summary>
    /// Verifies the HMAC signature on an incoming webhook request.
    /// Returns false if the signature does not match — the controller must return 400.
    /// </summary>
    bool VerifyWebhookSignature(string rawPayload, string providerSignature);

    /// <summary>
    /// Parses a raw provider webhook payload into a domain billing event.
    /// Returns null when the event type is not actionable (e.g. informational events).
    /// </summary>
    BillingWebhookEvent? ParseWebhookEvent(string rawPayload);

    /// <summary>
    /// Verifies a completed Paystack transaction by reference (callback-url flow).
    /// </summary>
    Task<VerifiedTransaction?> VerifyTransactionAsync(
        string reference,
        CancellationToken cancellationToken = default);
}

public record VerifiedTransaction(
    bool Success,
    string Reference,
    string? HouseholdId,
    SubscriptionTier? Tier,
    string ProviderEventId);

public record InitializeTransactionRequest(
    /// <summary>Household ID stored in Paystack metadata so we can route the webhook.</summary>
    string HouseholdId,
    /// <summary>Customer email address (required by Paystack).</summary>
    string Email,
    /// <summary>Amount in the provider's smallest currency unit (kobo for ZAR).</summary>
    long AmountInKobo,
    /// <summary>Unique reference generated by the caller (used for idempotency).</summary>
    string Reference,
    /// <summary>The tier the user is purchasing — stored in metadata.</summary>
    SubscriptionTier Tier,
    /// <summary>URL the provider redirects to after payment.</summary>
    string CallbackUrl);

public record InitializeTransactionResult(
    string AuthorizationUrl,
    string AccessCode,
    string Reference);

public record BillingWebhookEvent(
    string EventType,
    string HouseholdId,
    SubscriptionTier NewTier,
    DateTimeOffset EntitlementExpiresAt,
    string ProviderEventId);
